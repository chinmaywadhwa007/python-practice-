# Variables
a = 100
b = 45

# Addition
print("Addition:", a + b)  

# Subtraction
print("Subtraction:", a - b) 

# Multiplication
print("Multiplication:", a * b)  

# Division
print("Division:", a / b) 

# Floor Division
print("Floor Division:", a // b)  # we have the new term called the floor divison means where when the two variable divide by each other and then it value comes in points then it will round off to nearest value of the integer 

# Modulus
print("Modulus:", a % b) 

# Exponentiation
print("Exponentiation:", a ** b) # we have another new term called exponentiation 
# means raising a numbers to the power to the power of another number 